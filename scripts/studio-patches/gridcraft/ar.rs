pub(super) fn translate(text: &str) -> Option<&'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| {
        TABLE
            .iter()
            .map(|(en, ar)| {
                let shown: &'static str = Box::leak(crate::bidi::display_rtl(ar).into_boxed_str());
                (*en, shown)
            })
            .collect()
    })
    .get(text)
    .copied()
}
