/// Whether the interface is Arabic: the browser language on the web (the launcher sets it), the
/// `DECKCRAFT_LANGUAGE` or `LANG` variable elsewhere.
pub fn enabled() -> bool {
    static ON: OnceLock<bool> = OnceLock::new();
    *ON.get_or_init(detect)
}

#[cfg(target_arch = "wasm32")]
fn detect() -> bool {
    use js_sys::Reflect;
    let global = js_sys::global();
    Reflect::get(&global, &"navigator".into())
        .ok()
        .and_then(|nav| Reflect::get(&nav, &"language".into()).ok())
        .and_then(|lang| lang.as_string())
        .is_some_and(|lang| lang.to_ascii_lowercase().starts_with("ar"))
}

#[cfg(not(target_arch = "wasm32"))]
fn detect() -> bool {
    std::env::var("DECKCRAFT_LANGUAGE").or_else(|_| std::env::var("LANG")).is_ok_and(|lang| lang.to_ascii_lowercase().starts_with("ar"))
}

/// Break a label into two lines near the middle, the way the ribbon does for English
/// (`widgets::wrap_label`), but in logical order so the first words stay on top.
fn two_lines(text: &str) -> String {
    if text.contains('\n') {
        return text.to_owned();
    }
    let words: Vec<&str> = text.split(' ').collect();
    if words.len() < 2 || text.chars().count() <= 8 {
        return text.to_owned();
    }
    let mut best = 1;
    let mut best_diff = usize::MAX;
    for k in 1..words.len() {
        let a: usize = words.iter().take(k).map(|w| w.chars().count() + 1).sum();
        let b: usize = words.iter().skip(k).map(|w| w.chars().count() + 1).sum();
        let d = a.abs_diff(b);
        if d < best_diff {
            best_diff = d;
            best = k;
        }
    }
    let first = words.iter().take(best).copied().collect::<Vec<_>>().join(" ");
    let second = words.iter().skip(best).copied().collect::<Vec<_>>().join(" ");
    format!("{first}\n{second}")
}

fn build(wrap: bool) -> HashMap<&'static str, &'static str> {
    TABLE
        .iter()
        .map(|(en, ar)| {
            let logical = if wrap { two_lines(ar) } else { (*ar).to_owned() };
            let shown: &'static str = Box::leak(crate::bidi::display_rtl(&logical).into_boxed_str());
            (*en, shown)
        })
        .collect()
}

/// The Arabic for `text`, or `text` itself.
pub fn t(text: &str) -> &str {
    if !enabled() {
        return text;
    }
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| build(false)).get(text).copied().unwrap_or(text)
}

/// [`t`] for a ribbon button label: a long label is broken into two lines.
pub fn tb(text: &str) -> &str {
    if !enabled() {
        return text;
    }
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| build(true)).get(text).copied().unwrap_or(text)
}

/// The status bar's "Slide 3 of 10".
pub fn slide_of(index: usize, total: usize) -> String {
    if enabled() { crate::bidi::display_rtl(&format!("الشريحة {index} من {total}")) } else { format!("Slide {index} of {total}") }
}
