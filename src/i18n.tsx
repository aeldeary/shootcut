const dicts: Record<Lang, Record<Key, string>> = { en, ar };

/** A text in a chosen language, whatever the site is showing (used to search in both languages). */
export function textIn(lang: Lang, key: Key): string {
  return dicts[lang][key];
}

interface I18n {
  lang: Lang;
  dir: 'rtl' | 'ltr';
  t: (key: Key) => string;
  toggle: () => void;
}

const Ctx = createContext<I18n | null>(null);
const STORAGE_KEY = 'shootcut:lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ar' || saved === 'en') return saved;
  } catch {
    /* storage can be blocked; fall through */
  }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);
  const dir = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    document.title = dicts[lang].appName;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* ignore */
    }
  }, [lang, dir]);

  const t = useCallback((key: Key) => dicts[lang][key], [lang]);
  const toggle = useCallback(() => setLang((l) => (l === 'ar' ? 'en' : 'ar')), []);
  const value = useMemo(() => ({ lang, dir, t, toggle }) as I18n, [lang, dir, t, toggle]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n must be used inside I18nProvider');
  return v;
}
